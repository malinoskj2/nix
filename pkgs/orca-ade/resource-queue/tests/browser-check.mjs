// Run in the browser integration test page via Orca eval (never imported by production).
export async function check() {
  const results = [];
  const assert = (value, message) => { if (!value) throw new Error(message); results.push(message); };
  const settle = async () => { await new Promise((resolve) => setTimeout(resolve, 40)); };
  const press = async (selector) => { const el = document.querySelector(selector); assert(!!el, `Found ${selector}`); el.click(); await settle(); };
  await settle();
  assert(document.body.textContent.includes('● Live'), 'Live test bridge renders connected');
  assert(document.querySelectorAll('[role="tab"]').length === 4, 'Four views are available');
  assert(!document.querySelector('.mode'), 'Queue omits global admission controls');
  await press('[data-tab="resources"]');
  assert(document.querySelector('.capacity-grid') && !document.querySelector('.toolbar'), 'Resources separates capacity from the queue');
  assert(document.querySelectorAll('.resource-legend').length === 1, 'Resources has one shared usage legend');
  assert(document.querySelector('.capacity-grid').textContent.includes('Queue reserved'), 'Reservations remain separate from actual usage');
  await press('[data-action="refresh"]');
  assert(document.querySelector('#tab-resources').getAttribute('aria-selected') === 'true', 'Refresh preserves the selected tab');
  document.querySelector('#tab-resources').dispatchEvent(new KeyboardEvent('keydown', { key: 'ArrowRight', bubbles: true }));
  await settle();
  assert(document.activeElement.id === 'tab-history' && document.querySelector('#panel-history'), 'Arrow keys switch tabs and retain focus');
  assert(document.querySelector('.queue-section').textContent.includes('Recent history'), 'History shows completed jobs');
  assert([...document.querySelectorAll('#panel-history .badge.success')].some((badge) => badge.textContent === 'Completed'), 'History completed badge is green');
  assert(!document.querySelector('[data-action="export"], [data-action="exportJob"], .pressure, .capacity-note'), 'Removed controls and disclaimers stay absent');
  await press('[data-tab="queue"]');

  window.testBridge.raw.notifications = [{ id: '00000000000000000000000000000001', label: 'Detached completion', state: 'failed', exit_code: 7, notification: { state: 'unavailable', detail: 'Session unavailable' }, ready: true }];
  window.testBridge.raw.notification_count = 1;
  await press('[data-action="refresh"]');
  assert(document.querySelector('.completion-inbox').textContent.includes('Exit 7'), 'Completion inbox shows failure');
  await press('[data-notification-job]');
  assert(document.querySelector('.inspector'), 'Completion opens job inspection');
  await press('[data-action="ackNotification"]');
  assert(!document.querySelector('.completion-inbox'), 'Reviewed completion leaves inbox');
  await press('[data-tab="queue"]');

  const initialControls = window.testBridge.controls.length;
  await press('[data-action="run-next"][data-queue-job="00000000000000000000000000000004"]');
  assert(window.testBridge.controls.length === initialControls, 'Reorder waits for confirmation');
  await press('[data-action="confirm"]');
  assert(document.querySelector('[aria-label="Waiting"] .job-row').dataset.job.endsWith('04'), 'Run next moves the selected waiting row to the top');
  const afterReorder = window.testBridge.controls.length;
  await press('[data-job="00000000000000000000000000000003"]');
  assert(document.querySelector('.inspector').textContent.includes('Needs 10 GiB RAM'), 'Inspector retains exact wait reason');
  await press('[data-action="cancel"]');
  assert(window.testBridge.controls.length === afterReorder, 'Opening confirmation sends no command');
  assert(document.querySelector('[role="dialog"]'), 'Disruptive action requires confirmation');
  assert(document.activeElement.dataset.action === 'dismiss', 'Focus starts on safe dismissal');
  await press('[data-action="confirm"]');
  assert(window.testBridge.controls.length === afterReorder + 1, 'Confirmed action sends one command');
  assert(window.testBridge.controls[afterReorder].revision === 1, 'Confirmed command carries job revision');
  assert(document.querySelector('.inspector').textContent.includes('Cancelled'), 'Confirmed lifecycle replaces queued state');
  assert(!document.querySelector('.inspector [data-action="cancel"]'), 'Terminal job has no cancellation control');
  const input = document.getElementById('job-search');
  input.focus(); input.value = 'nixos'; input.dispatchEvent(new Event('input', { bubbles: true })); await settle();
  assert(document.querySelectorAll('.queue-section .job-row').length === 1, 'Search filters active queue');
  assert(document.activeElement.id === 'job-search', 'Typing retains input focus across redraw');
  input.value = ''; document.getElementById('job-search').value = ''; document.getElementById('job-search').dispatchEvent(new Event('input', { bubbles: true })); await settle();
  window.testBridge.disconnect();
  await press('[data-action="refresh"]');
  assert(document.body.textContent.includes('Connection interrupted'), 'Disconnect is visible');
  assert(document.body.textContent.includes('NixOS rebuild'), 'Disconnect preserves last known running jobs');
  assert(!document.querySelector('[data-action="pause"]'), 'Disconnected queue cannot pause admissions');
  window.testBridge.reconnect();
  await press('[data-action="refresh"]');
  assert(document.body.textContent.includes('● Live'), 'Reconnect recovers live view');
  await press('[data-tab="controls"]');
  assert(document.querySelector('#panel-controls .mode'), 'Controls contains scheduler admission status');
  await press('[data-action="pause"]');
  await press('[data-action="confirm"]');
  assert(document.body.textContent.includes('New admissions paused'), 'Confirmed admission hold rendered');
  assert(document.querySelector('[data-action="resume"]'), 'Resume appears only after confirmed hold');
  await press('[data-tab="queue"]');
  const runButton = document.querySelector('[data-action="force-run"][data-queue-job="00000000000000000000000000000004"]');
  runButton.dispatchEvent(new PointerEvent('pointerdown', { bubbles: true, pointerId: 1 }));
  await press('[data-action="refresh"]');
  assert(runButton.isConnected, 'Polling preserves the button between pointer down and click');
  runButton.dispatchEvent(new PointerEvent('pointerup', { bubbles: true, pointerId: 1 }));
  runButton.click();
  await settle();

  assert(!document.querySelector('.inspector'), 'Slurm run opens only confirmation');
  assert(document.querySelector('[role="dialog"]').textContent.includes('Slurm allocation limits still apply'), 'Slurm run explains remaining allocation limits');
  await press('[data-action="confirm"]');
  assert(!document.querySelector('[data-action="force-run"][data-queue-job="00000000000000000000000000000004"]'), 'Released Slurm allocation cannot be launched twice');
  assert(!document.querySelector('.inspector'), 'Slurm confirmation does not open inspection');
  const raw = window.testBridge.raw;
  raw.jobs.push({ ...structuredClone(raw.jobs[2]), id:'00000000000000000000000000000007', state:'queued', label:'Host launch check', revision:1, released:false, cleanup:null });
  await press('[data-action="refresh"]');
  await press('[data-action="run-host"][data-queue-job="00000000000000000000000000000007"]');
  assert(document.querySelector('[role="dialog"]').textContent.includes('outside the sandbox and Slurm'), 'Host run explicitly discloses execution boundary');
  await press('[data-action="confirm"]');
  assert(!document.querySelector('.inspector'), 'Host confirmation does not open inspection');
  await press('[data-job="00000000000000000000000000000007"]');
  assert(document.querySelector('.inspector').textContent.includes('Host · unmanaged'), 'Host handoff is visibly unmanaged');
  assert(document.querySelector('.inspector').textContent.includes('not enforced'), 'Host execution never claims a resource reservation');
  raw.jobs.push({ ...structuredClone(raw.jobs[2]), id:'00000000000000000000000000000008', origin:'agent-sandbox-test', state:'queued', label:'Sandbox launch check', revision:1, released:false, cleanup:null });
  await press('[data-action="refresh"]');
  await press('[data-action="run-sandbox"][data-queue-job="00000000000000000000000000000008"]');
  assert(document.querySelector('.inspector').textContent.includes('Host launch check'), 'Sandbox run preserves the previously inspected job');
  const beforeSandbox = window.testBridge.controls.length;
  assert(document.querySelector('[role="dialog"]').textContent.includes('original submitting sandbox, outside Slurm'), 'Sandbox run discloses its execution boundary');
  assert(document.querySelector('[role="dialog"]').textContent.includes('failure to enter it stops execution'), 'Sandbox run has no host fallback');
  await press('[data-action="confirm"]');
  assert(window.testBridge.controls.length === beforeSandbox + 1, 'Sandbox confirmation sends exactly one command');
  assert(window.testBridge.controls.at(-1).action === 'run-sandbox', 'Sandbox confirmation uses the distinct backend action');
  assert(document.querySelector('.inspector').textContent.includes('Host launch check'), 'Sandbox confirmation preserves the previously inspected job');
  assert(window.testBridge.controls.at(-1).id === '00000000000000000000000000000008', 'Confirmation targets the clicked job, not the inspected job');
  await press('[data-job="00000000000000000000000000000008"]');
  assert(document.querySelector('.inspector').textContent.includes('Sandbox · unmanaged'), 'Sandbox handoff is visibly unmanaged');
  assert(document.querySelector('.inspector').textContent.includes('not enforced'), 'Sandbox execution never claims a reservation');
  assert(!document.querySelector('[data-action="run-sandbox"][data-queue-job="00000000000000000000000000000008"]'), 'Sandbox handoff cannot launch twice');
  Object.assign(raw.jobs[0], { large_gpu_lane: true, profile_automatic: true, ram_admission: { basis: 'adaptive', growth_mib: 1024, learned_runs: 3 }, repo: 'riso-scene-workflow', worktree_name: 'Vue app', parent_worktree_name: 'UI migration', explore: true, profile: { project: 'nix', name: 'trial', variant: 'v1' }, failure: 'gpu_oom_reported' });
  await press('[data-action="refresh"]');
  await press('[data-job="00000000000000000000000000000001"]');
  assert(document.querySelector('.owner-child').textContent.includes('Vue app'), 'Queue shows indented child worktree');
  assert(document.querySelector('.inspector').textContent.includes('UI migration'), 'Inspector preserves parent name');
  assert(document.querySelector('.inspector').textContent.includes('riso-scene-workflow'), 'Inspector shows repository');
  assert(document.querySelector('.inspector').textContent.includes('Large GPU lane'), 'Large GPU exception is identified');
  assert(document.querySelector('.inspector').textContent.includes('Only critical headroom and severe pressure'), 'Large GPU exception explains relaxed admission');
  assert(document.querySelector('.inspector').textContent.includes('Automatic workload signature'), 'Automatic profile is visibly identified');
  assert(document.querySelector('.inspector').textContent.includes('3 completed samples'), 'Adaptive allowance reports its evidence');
  assert(document.querySelector('.inspector').textContent.includes('hard RAM limit remain unchanged'), 'Adaptive admission does not imply changing hard limits');
  assert(document.querySelector('.inspector').textContent.includes('Exploratory'), 'Trial badge appears in inspector');
  assert(document.querySelector('.inspector').textContent.includes('not a measured peak'), 'Trial budget is not presented as a measured peak');
  assert(document.querySelector('.inspector').textContent.includes('nix / trial / v1'), 'Profile settings identity appears in inspector');
  assert(document.querySelector('.inspector').textContent.includes('gpu oom reported'), 'Classified outcome appears in inspector');
  assert(document.documentElement.scrollWidth <= window.innerWidth, 'No horizontal overflow');
  return { passed: results.length, results };
}
